export const replyLang = (code = 'hi-IN') => (String(code).startsWith('en') ? 'en' : String(code).startsWith('kn') ? 'kn' : 'hi')
export const say = (lang, key, v = {}) => ({ hi, en, kn }[replyLang(lang)][key] ?? hi[key])(v)
